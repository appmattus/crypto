package com.appmattus.crypto

/**
 * Marks declarations that are public only so the cryptohash modules can share them. They are not part of
 * cryptohash's API and may change or be removed in any release.
 */
@RequiresOptIn(
    level = RequiresOptIn.Level.ERROR,
    message = "This is internal to the cryptohash modules and may change or be removed in any release"
)
@Retention(AnnotationRetention.BINARY)
@Target(
    AnnotationTarget.CLASS,
    AnnotationTarget.FUNCTION,
    AnnotationTarget.PROPERTY,
    AnnotationTarget.TYPEALIAS
)
public annotation class InternalCryptohash
